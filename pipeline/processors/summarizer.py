"""Aggregate frame context + transcript into summary, category, action data, tags,
and an embedding vector — all via Gemini. Dry-run mode uses local heuristics only."""

from __future__ import annotations

from pipeline import gemini_client
from pipeline.config import settings

CATEGORY_KEYWORDS = {
    "Tech": ["code", "python", "ai", "claude", "gpt", "api", "developer", "programming"],
    "Food": ["recipe", "cook", "pasta", "food", "ingredient", "butter"],
    "Fitness": ["workout", "gym", "exercise", "fitness", "muscle"],
    "Finance": ["money", "invest", "stock", "finance", "budget"],
    "Productivity": ["productivity", "habit", "focus", "time management"],
}


def generate_summary(
    transcript: str,
    visual_context: str,
    dry_run: bool | None = None,
) -> dict:
    """Generate summary, category, action_type/action_data, and tags via Gemini text
    generation. Dry-run uses local heuristics only (no API call)."""
    dry_run = settings.dry_run if dry_run is None else dry_run

    if dry_run:
        return _heuristic_summary(transcript, visual_context)

    return gemini_client.generate_summary(transcript, visual_context)


def _heuristic_summary(transcript: str, visual_context: str) -> dict:
    combined = f"{transcript}\n{visual_context}".lower()

    category = "Other"
    tags: list[str] = []
    for cat, terms in CATEGORY_KEYWORDS.items():
        hits = [t for t in terms if t in combined]
        if hits:
            if category == "Other":
                category = cat
            tags.extend(hits)

    if not tags:
        tags = ["reel", "saved", "video"]

    summary = (
        "[DRY-RUN] Summary would be generated by "
        f"{settings.gemini_text_model} from transcript and "
        f"{len(visual_context.splitlines())} frame descriptions. "
        f"Detected category hint: {category}."
    )

    return {
        "summary": summary,
        "category": category,
        "action_type": "general",
        "action_data": {
            "code": None,
            "language": None,
            "ingredients": [],
            "steps": [],
            "extracted_content": "[DRY-RUN] Structured breakdown would be generated here.",
        },
        "tags": list(dict.fromkeys(tags))[:10],
    }


def build_search_text(
    title: str,
    transcript: str,
    visual_context: str,
    summary: str,
    tags: list[str],
) -> str:
    parts = [
        f"Title: {title}",
        f"Summary: {summary}",
        f"Tags: {', '.join(tags)}",
        f"Transcript: {transcript}",
        f"Visual context:\n{visual_context}",
    ]
    return "\n\n".join(parts)


def generate_embedding(search_text: str, dry_run: bool | None = None) -> list[float]:
    dry_run = settings.dry_run if dry_run is None else dry_run
    if dry_run:
        return []
    return gemini_client.embed_text(search_text, task_type="RETRIEVAL_DOCUMENT")


def embed_query(query: str, dry_run: bool | None = None) -> list[float]:
    dry_run = settings.dry_run if dry_run is None else dry_run
    if dry_run:
        return []
    return gemini_client.embed_text(query, task_type="RETRIEVAL_QUERY")
