"""Audio transcription via Gemini native audio understanding — dry-run by default.

No Whisper / OpenAI call anywhere: Gemini 2.5 Flash accepts audio directly and
returns timestamped transcript segments, matching the frontend's TranscriptItem
shape ({ time, text }) directly.
"""

from __future__ import annotations

from pathlib import Path

from pipeline import gemini_client
from pipeline.config import settings
from pipeline.models import TranscriptSegment


def transcribe_audio(audio_path: Path | None, dry_run: bool | None = None) -> list[TranscriptSegment]:
    """Transcribe reel audio via Gemini's native audio understanding.

    dry_run=True returns a placeholder segment without any API call.
    """
    dry_run = settings.dry_run if dry_run is None else dry_run

    if dry_run or audio_path is None:
        return [
            TranscriptSegment(
                time=0,
                text=(
                    f"[DRY-RUN] Audio transcript would be generated by {settings.gemini_audio_model}. "
                    "This text anchors semantic search alongside visual frame context."
                ),
            )
        ]

    segments = gemini_client.transcribe_audio(audio_path)
    return [TranscriptSegment(time=s["time"], text=s["text"]) for s in segments]
